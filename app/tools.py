async def search(query: str) -> str:
    # модель нередко пишет «е» вместо «ё», поэтому выравниваем обе стороны
    q = query.lower().replace("ё", "е")
    matches = [
        f"{emp_id}: {card['имя']} — {card['должность']}"
        for emp_id, card in _EMPLOYEES.items()
        if q in card["имя"].lower().replace("ё", "е")
        or q in card["должность"].lower().replace("ё", "е")
    ]
    if not matches:
        return f"по запросу «{query}» никого не нашлось"
    return "\n".join(matches)


async def fetch_profile(user_id: str) -> dict:
    # копия, чтобы вызывающий не мог испортить исходные данные
    return dict(_EMPLOYEES[user_id])


